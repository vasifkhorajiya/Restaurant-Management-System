CREATE TABLE IF NOT EXISTS inventory_logs (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id     INT NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
  change_qty  NUMERIC(10,2) NOT NULL,
