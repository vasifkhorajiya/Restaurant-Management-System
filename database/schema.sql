-- =============================================================================
--  PART 0 — helper: keeps updated_at current (PostgreSQL has no ON UPDATE CURRENT_TIMESTAMP)
-- =============================================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =============================================================================
--  PART 1 — CORE: roles, restaurants, users
-- =============================================================================

CREATE TABLE IF NOT EXISTS roles (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(20) NOT NULL UNIQUE                 -- admin | manager | user
);

CREATE TABLE IF NOT EXISTS restaurants (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(150) NOT NULL,
  address       VARCHAR(255) NOT NULL,
  phone         VARCHAR(20)  NOT NULL,
  opening_time  TIME NOT NULL,
  closing_time  TIME NOT NULL,
  description   VARCHAR(255),
  cuisine       VARCHAR(120),
  is_open       BOOLEAN NOT NULL DEFAULT TRUE,     -- manager can pause new orders
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- admin, manager and customer logins all live here
CREATE TABLE IF NOT EXISTS users (
  id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                VARCHAR(100) NOT NULL,
  email               VARCHAR(150) NOT NULL UNIQUE,
  password            VARCHAR(255) NOT NULL,                 -- bcrypt hash
  phone               VARCHAR(20) UNIQUE,                    -- +<country code><10 digits>, e.g. +919876543210 (one account per number)
  role_id             INT NOT NULL REFERENCES roles(id),
  restaurant_id       INT REFERENCES restaurants(id) ON DELETE SET NULL,   -- only set for managers
  status              VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','blocked')),
  failed_attempts     INT NOT NULL DEFAULT 0,                -- brute-force counter
  locked_until        TIMESTAMPTZ,
  loyalty_points      INT NOT NULL DEFAULT 0,
  last_login          TIMESTAMPTZ,
  password_changed_at TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_users_email_lower CHECK (email = LOWER(email))   -- PostgreSQL text is case-sensitive; the app always stores lower-case
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role_id);
CREATE INDEX IF NOT EXISTS idx_users_restaurant ON users(restaurant_id);

-- =============================================================================
--  PART 2 — MENU: categories, menu_items, staff
-- =============================================================================

CREATE TABLE IF NOT EXISTS categories (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name          VARCHAR(100) NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uniq_category_per_restaurant UNIQUE (restaurant_id, name)
);

CREATE TABLE IF NOT EXISTS menu_items (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id     INT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  category_id       INT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  name              VARCHAR(150) NOT NULL,
  description       VARCHAR(500),
  price             NUMERIC(10,2) NOT NULL,
  discount_percent  SMALLINT NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 90),
  is_veg            BOOLEAN NOT NULL DEFAULT TRUE,
  spice_level       SMALLINT NOT NULL DEFAULT 0 CHECK (spice_level BETWEEN 0 AND 3),   -- 0 none · 1 mild · 2 medium · 3 hot
  prep_time_min     SMALLINT NOT NULL DEFAULT 15 CHECK (prep_time_min > 0),
  is_featured       BOOLEAN NOT NULL DEFAULT FALSE,           -- "Chef's pick"
  stock_qty         INT CHECK (stock_qty IS NULL OR stock_qty >= 0),   -- NULL = unlimited; 0 = sold out
  image_url         VARCHAR(500),
  is_available      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_menu_restaurant ON menu_items(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_menu_category ON menu_items(category_id);
CREATE INDEX IF NOT EXISTS idx_menu_available ON menu_items(is_available);

-- restaurant staff (NOT login accounts). Position "Delivery"/"Rider" makes them assignable to deliveries.
CREATE TABLE IF NOT EXISTS staff (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name          VARCHAR(100) NOT NULL,
  email         VARCHAR(150),
  phone         VARCHAR(20),
  position      VARCHAR(50) NOT NULL,
  shift         VARCHAR(10) NOT NULL DEFAULT 'Flexible' CHECK (shift IN ('Morning','Evening','Night','Flexible')),
  salary        NUMERIC(10,2),
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  joined_on     DATE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
--  PART 3 — ORDERS, PAYMENTS, REVIEWS
-- =============================================================================

CREATE TABLE IF NOT EXISTS orders (
  id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id        INT NOT NULL REFERENCES users(id),
  restaurant_id      INT NOT NULL REFERENCES restaurants(id),
  status             VARCHAR(10) NOT NULL DEFAULT 'Pending'
                       CHECK (status IN ('Pending','Accepted','Preparing','Ready','Completed','Cancelled')),
  order_type         VARCHAR(10) NOT NULL DEFAULT 'Delivery' CHECK (order_type IN ('Delivery','Pickup','Dine-in')),
  source             VARCHAR(10) NOT NULL DEFAULT 'Online'   CHECK (source IN ('Online','POS')),
  delivery_address   VARCHAR(255),
  table_no           VARCHAR(20),
  notes              VARCHAR(255),
  subtotal           NUMERIC(10,2) NOT NULL DEFAULT 0,
  discount_amount    NUMERIC(10,2) NOT NULL DEFAULT 0,
  coupon_code        VARCHAR(40),
  tax_amount         NUMERIC(10,2) NOT NULL DEFAULT 0,
  delivery_fee       NUMERIC(10,2) NOT NULL DEFAULT 0,
  tip_amount         NUMERIC(10,2) NOT NULL DEFAULT 0,
  points_used        INT NOT NULL DEFAULT 0,
  points_earned      INT NOT NULL DEFAULT 0,
  points_awarded     BOOLEAN NOT NULL DEFAULT FALSE,
  total_amount       NUMERIC(10,2) NOT NULL,                  -- what the customer actually pays
  eta_minutes        SMALLINT NOT NULL DEFAULT 30,
  scheduled_for      TIMESTAMPTZ,                             -- "order for later"
  handover_code      CHAR(4),                                 -- customer reads this out at delivery/pickup
  handover_attempts  SMALLINT NOT NULL DEFAULT 0,
  rider_id           INT REFERENCES staff(id) ON DELETE SET NULL,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_restaurant ON orders(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders(created_at);

CREATE TABLE IF NOT EXISTS order_items (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      INT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  menu_item_id  INT NOT NULL REFERENCES menu_items(id),
  quantity      INT NOT NULL DEFAULT 1 CHECK (quantity > 0),
  price         NUMERIC(10,2) NOT NULL                        -- price at time of order (snapshot)
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS order_status_history (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status      VARCHAR(20) NOT NULL,
  changed_by  INT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_osh_order ON order_status_history(order_id);

CREATE TABLE IF NOT EXISTS payments (
  id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id            INT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  amount              NUMERIC(10,2) NOT NULL,
  method              VARCHAR(12) NOT NULL DEFAULT 'Cash' CHECK (method IN ('Cash','Card','UPI','Wallet','Netbanking')),
  status              VARCHAR(10) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Paid','Failed','Refunded')),
  paid_at             TIMESTAMPTZ,
  transaction_ref     VARCHAR(60),
  gateway_order_id    VARCHAR(40),                            -- fake Razorpay: order_xxxx
  gateway_payment_id  VARCHAR(40),                            -- fake Razorpay: pay_xxxx
  gateway_signature   VARCHAR(128),                           -- HMAC-SHA256 that was verified
  card_last4          CHAR(4),                                -- only the last 4 digits are ever stored
  card_network        VARCHAR(20),
  upi_masked          VARCHAR(60),
  refund_id           VARCHAR(40),                            -- rfnd_xxxx
  refunded_at         TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_payments_order ON payments(order_id);

-- fake Razorpay "orders" created before the customer pays (the cart is re-priced again on verify)
CREATE TABLE IF NOT EXISTS payment_orders (
  id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gateway_order_id    VARCHAR(40) NOT NULL UNIQUE,
  user_id             INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  amount_paise        INT NOT NULL,
  currency            CHAR(3) NOT NULL DEFAULT 'INR',
  status              VARCHAR(10) NOT NULL DEFAULT 'created' CHECK (status IN ('created','attempted','paid','failed','expired')),
  payload             TEXT NOT NULL,                          -- checkout (cart) snapshot
  attempts            SMALLINT NOT NULL DEFAULT 0,
  method              VARCHAR(20),
  pending_txn         VARCHAR(40),                            -- card waiting for its 3-D Secure OTP
  card_last4          CHAR(4),
  card_network        VARCHAR(20),
  upi_masked          VARCHAR(60),
  bank                VARCHAR(40),
  gateway_payment_id  VARCHAR(40),
  failure_reason      VARCHAR(120),
  order_id            INT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at          TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS refund_requests (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        INT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  user_id         INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reason          VARCHAR(255) NOT NULL,
  status          VARCHAR(10) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected')),
  resolved_by     INT,
  resolution_note VARCHAR(255),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at     TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS reviews (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      INT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,   -- one review per order
  customer_id   INT NOT NULL REFERENCES users(id),
  rating        SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review        TEXT,
  admin_reply   TEXT,
  replied_at    TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
--  PART 4 — DINING: tables, reservations, live service requests
-- =============================================================================

CREATE TABLE IF NOT EXISTS restaurant_tables (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  table_no      VARCHAR(20) NOT NULL,
  capacity      INT NOT NULL DEFAULT 4 CHECK (capacity > 0),
  status        VARCHAR(12) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Occupied','Reserved','Maintenance')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uniq_table_per_restaurant UNIQUE (restaurant_id, table_no)
);

CREATE TABLE IF NOT EXISTS reservations (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id       INT NOT NULL REFERENCES users(id),
  restaurant_id     INT NOT NULL REFERENCES restaurants(id),
  table_id          INT REFERENCES restaurant_tables(id) ON DELETE SET NULL,   -- auto-assigned, manager can change
  party_size        INT NOT NULL CHECK (party_size > 0),
  reservation_date  DATE NOT NULL,
  reservation_time  TIME NOT NULL,
  status            VARCHAR(10) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Confirmed','Cancelled','Completed')),
  special_request   VARCHAR(255),
  manager_note      VARCHAR(255),
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_reservations_restaurant ON reservations(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_reservations_customer ON reservations(customer_id);
CREATE INDEX IF NOT EXISTS idx_reservations_date ON reservations(reservation_date);

-- "Call waiter" / "Request bill" taps from a dine-in customer — pushed live to the staff screen
CREATE TABLE IF NOT EXISTS service_requests (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  order_id      INT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  user_id       INT NOT NULL,
  table_no      VARCHAR(20),
  type          VARCHAR(10) NOT NULL DEFAULT 'Waiter' CHECK (type IN ('Waiter','Bill','Water','Help')),
  status        VARCHAR(10) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Done')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  done_at       TIMESTAMPTZ,
  done_by       INT
);
CREATE INDEX IF NOT EXISTS idx_sr_open ON service_requests(restaurant_id, status);

-- =============================================================================
--  PART 5 — CUSTOMER EXTRAS: coupons, addresses, favourites, notifications
-- =============================================================================

CREATE TABLE IF NOT EXISTS coupons (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  INT REFERENCES restaurants(id) ON DELETE CASCADE,         -- NULL = valid at every restaurant
  code           VARCHAR(40) NOT NULL UNIQUE,
  description    VARCHAR(255),
  discount_type  VARCHAR(10) NOT NULL DEFAULT 'percent' CHECK (discount_type IN ('percent','flat')),
  discount_value NUMERIC(10,2) NOT NULL,
  min_order      NUMERIC(10,2) NOT NULL DEFAULT 0,
  max_discount   NUMERIC(10,2),
  usage_limit    INT,                                                       -- NULL = unlimited total uses
  used_count     INT NOT NULL DEFAULT 0,
  per_user_limit INT NOT NULL DEFAULT 1,
  valid_from     DATE,
  valid_until    DATE,
  is_active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS coupon_usages (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coupon_id  INT NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
  user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  order_id   INT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_cu_coupon_user ON coupon_usages(coupon_id, user_id);

CREATE TABLE IF NOT EXISTS customer_addresses (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label        VARCHAR(30) NOT NULL DEFAULT 'Home',
  address_line VARCHAR(255) NOT NULL,
  landmark     VARCHAR(120),
  is_default   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS favorites (
  user_id      INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  menu_item_id INT NOT NULL REFERENCES menu_items(id) ON DELETE CASCADE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, menu_item_id)
);

CREATE TABLE IF NOT EXISTS notifications (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      VARCHAR(120) NOT NULL,
  message    VARCHAR(255) NOT NULL,
  type       VARCHAR(30) NOT NULL DEFAULT 'info',
  link       VARCHAR(120),
  is_read    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_notif_user_read ON notifications(user_id, is_read);

-- =============================================================================
