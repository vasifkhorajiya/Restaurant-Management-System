-- =============================================================================
--  SPICE ROUTE — RESTAURANT MANAGEMENT SYSTEM
--  Complete PostgreSQL schema (single file)  ·  PostgreSQL 13 or newer
-- =============================================================================
--  HOW TO RUN  (pick ONE way)
--
--  A) pgAdmin 4  (graphical)
--     1. Right-click  Databases ▸ Create ▸ Database…  → name it  restaurant_management  → Save.
--     2. Click the new database, then  Tools ▸ Query Tool.
--     3. Open this file (folder icon) — or paste it — and press ▶ Execute (F5).
--     4. Refresh the tree: restaurant_management ▸ Schemas ▸ public ▸ Tables → 30 tables.
--
--  B) One command from the project  (creates the database AND runs this file)
--        cd backend
--        npm run db:setup
--
--  C) psql
--        psql -U postgres -c "CREATE DATABASE restaurant_management;"
--        psql -U postgres -d restaurant_management -f database/schema.sql
--
--  Then:  cd backend  ▸  npm run seed   (creates the first admin login)
--
--  This ONE file contains every table, index, trigger and the starter data.
--  Re-running is safe: everything uses IF NOT EXISTS / ON CONFLICT DO NOTHING.
--  To rebuild from scratch, run the next two lines FIRST (this DELETES all data):
--        DROP SCHEMA public CASCADE;  CREATE SCHEMA public;
