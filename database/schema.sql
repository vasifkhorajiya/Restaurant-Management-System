CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs(created_at);

-- =============================================================================
--  PART 7 — SECURITY: password-reset links, sessions, delivery log, security timeline
-- =============================================================================

-- "Forgot password" links: only a SHA-256 hash of the token is stored; each link works once and expires in 1 hour
CREATE TABLE IF NOT EXISTS password_resets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  used       BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_pr_token ON password_resets(token_hash);

-- server-side sessions: logout / "sign out this device" / password reset revoke a login instantly
CREATE TABLE IF NOT EXISTS user_sessions (
  id         UUID PRIMARY KEY,
  user_id    INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ip         VARCHAR(45),
  user_agent VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  revoked    BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON user_sessions(user_id, revoked);

-- every email / SMS the system sends (receipts, status updates, reset links…) — recipient is masked, the message body is NOT stored
CREATE TABLE IF NOT EXISTS notification_log (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT,
  channel    VARCHAR(5)  NOT NULL CHECK (channel IN ('email','sms')),
  recipient  VARCHAR(80) NOT NULL,                            -- masked, e.g. ra***@gmail.com / +91 ••••••3210
  kind       VARCHAR(40) NOT NULL,                            -- order_placed, order_ready, password_reset …
  status     VARCHAR(6)  NOT NULL CHECK (status IN ('sent','demo','failed')),   -- demo = provider not configured, nothing left the server
  error      VARCHAR(200),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_nlog_created ON notification_log(created_at);
CREATE INDEX IF NOT EXISTS idx_nlog_user ON notification_log(user_id);

CREATE TABLE IF NOT EXISTS security_events (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT,
  email      VARCHAR(150),
  event      VARCHAR(40) NOT NULL,
  ip         VARCHAR(45),
  user_agent VARCHAR(255),
  details    VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_secev_user ON security_events(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_secev_created ON security_events(created_at);

